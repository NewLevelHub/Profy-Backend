async def seed_simulations():
    async with async_session() as session:
        for sim_data in SIMULATIONS:
            result = await session.execute(
                select(ProfessionSimulation).where(
                    ProfessionSimulation.leaf_slug == sim_data["leaf_slug"]
                )
            )
            sim = result.scalar_one_or_none()
            if sim is None:
                sim = ProfessionSimulation(
                    leaf_slug=sim_data["leaf_slug"],
                    steps=sim_data["steps"],
                )
                session.add(sim)
                print(f"Created simulation for {sim_data['leaf_slug']}")
            else:
                sim.steps = sim_data["steps"]
                print(f"Updated simulation for {sim_data['leaf_slug']}")
        await session.commit()


if __name__ == "__main__":
    asyncio.run(seed_simulations())
