async def seed_known_profession_quizzes():
    async with async_session() as session:
        for quiz_data in QUIZZES:
            result = await session.execute(
                select(KnownProfessionQuiz).where(
                    KnownProfessionQuiz.leaf_slug == quiz_data["leaf_slug"]
                )
            )
            quiz = result.scalar_one_or_none()
            if quiz is None:
                quiz = KnownProfessionQuiz(
                    leaf_slug=quiz_data["leaf_slug"],
                    questions=quiz_data["questions"],
                )
                session.add(quiz)
                print(f"Created known-profession quiz for {quiz_data['leaf_slug']}")
            else:
                quiz.questions = quiz_data["questions"]
                print(f"Updated known-profession quiz for {quiz_data['leaf_slug']}")
        await session.commit()

    print(f"Done: {len(QUIZZES)} known-profession quizzes seeded.")


if __name__ == "__main__":
    asyncio.run(seed_known_profession_quizzes())
