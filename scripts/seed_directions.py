async def main() -> None:
    async with async_session() as db:
        inserted = 0
        updated = 0
        skipped = 0

        for data in DIRECTIONS:
            result = await db.execute(
                select(Direction).where(Direction.slug == data["slug"])
            )
            existing = result.scalar_one_or_none()

            if existing is not None:
                changed = False
                for field in (
                    "name", "description", "required_scores", "bonus_scores",
                    "professions", "skills_needed", "subjects_to_develop", "first_steps",
                ):
                    if getattr(existing, field) != data[field]:
                        setattr(existing, field, data[field])
                        changed = True
                if changed:
                    updated += 1
                else:
                    skipped += 1
                continue

            db.add(Direction(**data))
            inserted += 1

        await db.commit()
        print(
            f"Done. Inserted: {inserted}, updated: {updated}, "
            f"skipped (unchanged): {skipped}"
        )
        print(f"Total directions in bank: {len(DIRECTIONS)}")


if __name__ == "__main__":
    asyncio.run(main())
