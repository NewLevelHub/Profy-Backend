def _hash(document: dict) -> str:
    canonical = json.dumps(document, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _key(phrase: str) -> str:
    return " ".join(phrase.split()).casefold()


def _with_additions(document: dict) -> dict:
    document = copy.deepcopy(document)
    for subtest in document["subtests"]:
        if subtest["key"] != "generalization":
            continue
        for item in subtest["items"]:
            for tier, by_locale in _ADDITIONS.get(item["item_id"], {}).items():
                for locale, phrases in by_locale.items():
                    accepted = {_key(p) for t in ("score_2", "score_1") for p in item[t].get(locale, [])}
                    new = [p for p in phrases if _key(p) not in accepted]
                    item[tier] = {**item[tier], locale: [*item[tier].get(locale, []), *new]}
    return document


def _versions() -> sa.TableClause:
    status = postgresql.ENUM("draft", "published", name="astur_bank_version_status_enum", create_type=False)
    return sa.table(
        "astur_bank_versions",
        sa.column("id", postgresql.UUID(as_uuid=True)),
        sa.column("version", sa.Integer()),
        sa.column("status", status),
        sa.column("document", postgresql.JSONB()),
        sa.column("content_hash", sa.String(64)),
        sa.column("based_on_id", postgresql.UUID(as_uuid=True)),
        sa.column("notes", sa.Text()),
        sa.column("published_at", sa.DateTime(timezone=True)),
    )


def upgrade() -> None:
    versions = _versions()
    connection = op.get_bind()
    if connection.execute(sa.select(versions.c.id).where(versions.c.id == _VERSION_ID)).scalar_one_or_none():
        return

    latest = connection.execute(
        sa.select(versions.c.id, versions.c.version, versions.c.document)
        .where(versions.c.status == "published")
        .order_by(versions.c.version.desc())
        .limit(1)
    ).one()
    document = _with_additions(latest.document)

    op.execute(
        versions.insert().values(
            id=_VERSION_ID,
            version=latest.version + 1,
            status="published",
            document=document,
            content_hash=_hash(document),
            based_on_id=latest.id,
            notes=(
                "«Обобщение»: добавлены принимаемые формулировки ответов на ru и kk "
                "(синонимы, число и порядок слов, казахские формы); задания, ключи "
                "остальных субтестов, таймеры и порядок не изменены."
            ),
            published_at=sa.func.now(),
        )
    )

    drafts = connection.execute(
        sa.select(versions.c.id, versions.c.document).where(versions.c.status == "draft")
    ).all()
    for draft_id, draft_document in drafts:
        if _hash(draft_document) == _hash(latest.document):
            values = {"document": document, "based_on_id": _VERSION_ID}
        else:
            values = {"document": _with_additions(draft_document)}
        op.execute(versions.update().where(versions.c.id == draft_id).values(**values))


def downgrade() -> None:
    versions = _versions()
    connection = op.get_bind()
    published = connection.execute(
        sa.select(versions.c.document, versions.c.based_on_id).where(versions.c.id == _VERSION_ID)
    ).one_or_none()
    if published is None:
        return
    previous = connection.execute(
        sa.select(versions.c.document).where(versions.c.id == published.based_on_id)
    ).scalar_one()
    # A draft re-based by upgrade goes back to being a copy of the previous
    # version; one with methodologist edits keeps the phrasings (valid
    # answers either way) but must stop pointing at the deleted version.
    rebased = connection.execute(
        sa.select(versions.c.id, versions.c.document).where(versions.c.based_on_id == _VERSION_ID)
    ).all()
    for draft_id, draft_document in rebased:
        values = {"based_on_id": published.based_on_id}
        if _hash(draft_document) == _hash(published.document):
            values["document"] = previous
        op.execute(versions.update().where(versions.c.id == draft_id).values(**values))
    op.execute(versions.delete().where(versions.c.id == _VERSION_ID))
