def _direction_brief(direction: Direction) -> dict:
    return {
        "name": direction.name,
        "description": direction.description,
        "professions": list(direction.professions or []),
        "skills_needed": list(direction.skills_needed or []),
        "subjects_to_develop": list(direction.subjects_to_develop or []),
    }


def build_messages(
    context: StudentContext,
    direction: Direction,
    university_requirements: list[UniversityRequirement] | None = None,
    selected_program: dict | None = None,
) -> list[dict[str, str]]:
    allowed = ", ".join(CATEGORIES)
    goal_focus = _GOAL_FOCUS.get(context.goal, "")
    system_content = f"{_SYSTEM_PROMPT}\n\n{goal_focus}" if goal_focus else _SYSTEM_PROMPT

    user_sections = [
        f"НАПРАВЛЕНИЕ:\n{json.dumps(_direction_brief(direction), ensure_ascii=False, indent=2)}",
        f"УЧЕНИК (все, что мы о нём знаем):\n{context.model_dump_json(indent=2)}",
    ]
    if university_requirements:
        # Real facts from Program/University, computed by the backend — never a
        # model decision, same principle as `_direction_brief` above. Only ever
        # non-empty for goal="university" (see roadmap_builder._generate_plan).
        reqs_payload = [r.model_dump() for r in university_requirements]
        user_sections.append(
            "ДАННЫЕ ПО ВУЗАМ (проверенные факты, НЕ придумывай ничего сверх этого):\n"
            f"{json.dumps(reqs_payload, ensure_ascii=False, indent=2)}"
        )
    if selected_program:
        user_sections.append(
            "ВЫБРАННАЯ ПРОГРАММА (для блока program_fit; извлекай только явно "
            "названные в требованиях предметы):\n"
            f"{json.dumps(selected_program, ensure_ascii=False, indent=2)}"
        )
    user_sections.append(
        f"Разрешённые значения category: {allowed}.\n\n"
        "Построй для этого ученика план развития в этом направлении по схеме."
    )
    user_content = "\n\n".join(user_sections)

    return [
        {"role": "system", "content": system_content},
        {"role": "user", "content": user_content},
    ]
